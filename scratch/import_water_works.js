async function runImport() {
  console.log('Initializing Database...');
  await initDb();

  const existingWorks = getWorks();
  console.log(`Currently in database: ${existingWorks.length} works.`);

  // Existing workCode set
  const existingCodes = new Set(existingWorks.map(w => (w.workCode || '').trim()).filter(Boolean));

  let insertedCount = 0;
  let skippedCount = 0;

  for (const item of waterWorksData) {
    if (item.workCode && existingCodes.has(item.workCode.trim())) {
      console.log(`Skipping duplicate workCode: ${item.workCode}`);
      skippedCount++;
      continue;
    }

    const budget = Number(item.budget) || 0;
    const spent = Number(item.spent) || budget;
    const panchayatShare = Math.round(budget * 0.1);
    const balance = Math.max(0, budget - spent);

    const workObj = {
      title: item.title,
      scheme: item.scheme,
      budget,
      spent,
      panchayatShare,
      balance,
      status: item.status,
      category: item.category,
      length: 'मानक पेयजल एवं संधारण कार्य',
      workType: 'पेयजल, बोरवेल एवं जल संरक्षण',
      contractor: 'ग्राम पंचायत काकोड़ा',
      startDate: item.startDate,
      endDate: item.endDate,
      progress: item.progress,
      image: '',
      description: item.description,
      workCode: item.workCode,
      sanctionNo: item.sanctionNo,
      location: item.location,
      sarpanchSign: 'संदीप कुमार (सरपंच)',
      secretarySign: 'रवि / ग्राम विकास अधिकारी',
      vouchers: [
        {
          voucherNo: `${item.workCode.replace(/[^a-zA-Z0-9]/g, '').slice(-6)}/V1`,
          date: item.sanctionDate,
          agency: 'ग्राम पंचायत पेयजल प्रबंधन समिति',
          purpose: item.title,
          amount: spent,
          sarpanchSign: 'संदीप कुमार',
          secretarySign: 'रवि'
        }
      ],
      documents: [
        {
          title: `प्रशासनिक व वित्तीय स्वीकृति (${item.sanctionNo})`,
          url: '',
          meta: `कार्य कोड: ${item.workCode} | स्वीकृत राशि: ₹${budget.toLocaleString('en-IN')}`
        }
      ]
    };

    const added = addWork(workObj);
    existingCodes.add(item.workCode);
    insertedCount++;
    console.log(`[+Added ID ${added.id}] [P.${item.page}] ${item.workCode}: ${item.title.substring(0, 42)}...`);
  }

  // Update overall stats
  const allUpdatedWorks = getWorks();
  const totalWorks = allUpdatedWorks.length;
  const completedWorks = allUpdatedWorks.filter(w => w.status === 'पूर्ण').length;
  const ongoingWorks = allUpdatedWorks.filter(w => w.status === 'चालू').length;

  const currentStats = getSetting('stats', {});
  const newStats = {
    ...currentStats,
    totalWorks,
    completedWorks,
    ongoingWorks
  };
  setSetting('stats', newStats);

  // Sync to db.json
  const jsonSeedPath = path.join(__dirname, '../data/db.json');
  if (fs.existsSync(jsonSeedPath)) {
    try {
      const jData = JSON.parse(fs.readFileSync(jsonSeedPath, 'utf8'));
      jData.works = allUpdatedWorks;
      jData.stats = {
        ...(jData.stats || {}),
        totalWorks,
        completedWorks,
        ongoingWorks
      };
      fs.writeFileSync(jsonSeedPath, JSON.stringify(jData, null, 2), 'utf8');
      console.log('Successfully synced all works and stats to data/db.json');
    } catch (e) {
      console.error('Error syncing to db.json:', e);
    }
  }

  console.log('\n====================================');
  console.log('WATER WORKS IMPORT COMPLETE');
  console.log(`Newly Inserted: ${insertedCount}`);
  console.log(`Skipped (Duplicates): ${skippedCount}`);
  console.log(`Total Works in System: ${totalWorks}`);
  console.log(`Completed Works: ${completedWorks}`);
  console.log(`Ongoing Works: ${ongoingWorks}`);
  console.log('====================================\n');
}

runImport().catch(console.error);
